// Rewrites the M3 colour roles in src/tokens.css: tonal spot, but the primary
// palette keeps the seed chroma. Standard contrast fills the light and dark
// blocks; medium and high contrast are appended as `data-contrast` presets.
import { readFile, writeFile } from "node:fs/promises";
import {
  DynamicScheme,
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
  TonalPalette,
  argbFromHex,
  hexFromArgb,
} from "@material/material-color-utilities";

const SEED = process.argv[2] ?? "#5B4CF0";
const PATH = "src/tokens.css";
const START = "/* contrast presets: generated by npm run colors */";
const END = "/* end contrast presets */";
const camel = (role) => role.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const scheme = (dark, contrastLevel) => {
  const base = new SchemeTonalSpot(
    Hct.fromInt(argbFromHex(SEED)),
    dark,
    contrastLevel,
  );
  return new DynamicScheme({
    sourceColorHct: base.sourceColorHct,
    variant: base.variant,
    contrastLevel,
    isDark: dark,
    primaryPalette: TonalPalette.fromInt(argbFromHex(SEED)),
    secondaryPalette: base.secondaryPalette,
    tertiaryPalette: base.tertiaryPalette,
    neutralPalette: base.neutralPalette,
    neutralVariantPalette: base.neutralVariantPalette,
  });
};

const source = await readFile(PATH, "utf8");
const darkStart = source.indexOf(':root[data-theme="dark"]');
if (darkStart === -1) throw new Error("The dark theme block is missing.");
const regionStart = source.indexOf(START);
const body = regionStart === -1 ? source : source.slice(0, regionStart);

const recolor = (text, s) =>
  text.replace(
    /(--md-sys-color-([a-z-]+):\s*)#[0-9a-fA-F]{3,8}/g,
    (all, head, role) => {
      const color = MaterialDynamicColors[camel(role)];
      return color ? head + hexFromArgb(color.getArgb(s)) : all;
    },
  );

const standard =
  recolor(body.slice(0, darkStart), scheme(false, 0)) +
  recolor(body.slice(darkStart), scheme(true, 0));

const roles = [
  ...new Set(
    [
      ...standard.slice(0, darkStart).matchAll(/--md-sys-color-([a-z-]+):/g),
    ].map((match) => match[1]),
  ),
];
if (!roles.length) throw new Error("No colour roles found in the light block.");

const preset = (selector, dark, contrastLevel) => {
  const s = scheme(dark, contrastLevel);
  const rows = roles
    .map((role) => {
      const color = MaterialDynamicColors[camel(role)];
      return color
        ? `  --md-sys-color-${role}: ${hexFromArgb(color.getArgb(s))};`
        : null;
    })
    .filter(Boolean);
  return `${selector} {${dark ? "\n  color-scheme: dark;" : ""}\n${rows.join("\n")}\n}`;
};

const region = [
  START,
  preset(':root[data-contrast="medium"]', false, 0.5),
  preset(':root[data-theme="dark"][data-contrast="medium"]', true, 0.5),
  preset(':root[data-contrast="high"]', false, 1),
  preset(':root[data-theme="dark"][data-contrast="high"]', true, 1),
  END,
].join("\n");

await writeFile(PATH, `${standard.trimEnd()}\n\n${region}\n`);
console.log(
  `Colour roles regenerated from seed ${SEED} with standard, medium and high contrast.`,
);

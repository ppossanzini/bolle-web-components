// Samples the Material spring definitions in src/tokens.css into CSS linear()
// easings: CSS cannot express damping and stiffness, so each pair becomes an
// easing curve plus the time it takes to settle.
import { readFile, writeFile } from "node:fs/promises";

const PATH = "src/tokens.css";
const START = "  /* spring easings: generated by npm run motion */";
const END = "  /* end spring easings */";
const SPRING =
  /--md-sys-motion-spring-(default|fast|slow)-(spatial|effects)-(damping|stiffness):\s*([\d.]+);/g;
const SETTLED = 0.0015;
const MAX_SECONDS = 2;

const response = (seconds, damping, stiffness) => {
  const w0 = Math.sqrt(stiffness);
  if (damping >= 1) return 1 - Math.exp(-w0 * seconds) * (1 + w0 * seconds);
  const wd = w0 * Math.sqrt(1 - damping * damping);
  return (
    1 -
    Math.exp(-damping * w0 * seconds) *
      (Math.cos(wd * seconds) + ((damping * w0) / wd) * Math.sin(wd * seconds))
  );
};

const settle = (damping, stiffness) => {
  for (let ms = 16; ms <= MAX_SECONDS * 1000; ms += 4) {
    let stable = true;
    for (let extra = 0; extra <= 120; extra += 20) {
      if (
        Math.abs(1 - response((ms + extra) / 1000, damping, stiffness)) >
        SETTLED
      ) {
        stable = false;
        break;
      }
    }
    if (stable) return ms;
  }
  return MAX_SECONDS * 1000;
};

const easing = (damping, stiffness) => {
  const duration = settle(damping, stiffness);
  const points = ["0"];
  for (let step = 1; step <= 20; step += 1) {
    const at = step / 20;
    const value = response((at * duration) / 1000, damping, stiffness);
    points.push(
      `${Number(value.toFixed(4))} ${Number((at * 100).toFixed(1))}%`,
    );
  }
  return { curve: `linear(${points.join(", ")})`, duration };
};

const source = await readFile(PATH, "utf8");
const tokens = [...source.matchAll(SPRING)];
if (!tokens.length)
  throw new Error("No spring tokens found in src/tokens.css.");

const springs = new Map();
for (const [, size, kind, field, value] of tokens) {
  const key = `${size}-${kind}`;
  springs.set(key, { ...springs.get(key), [field]: Number(value) });
}

const lines = [START];
for (const size of ["default", "fast", "slow"]) {
  for (const kind of ["spatial", "effects"]) {
    const spring = springs.get(`${size}-${kind}`);
    if (!spring)
      throw new Error(`Incomplete spring definition: ${size}-${kind}.`);
    const { curve, duration } = easing(spring.damping, spring.stiffness);
    lines.push(
      `  --md-sys-motion-spring-${size}-${kind}-duration: ${duration}ms;`,
      `  --md-sys-motion-spring-${size}-${kind}-easing: ${curve};`,
    );
  }
}
for (const kind of ["spatial", "effects"]) {
  lines.push(
    `  --bb-spring-${kind}: var(--md-sys-motion-spring-default-${kind}-easing);`,
    `  --bb-spring-${kind}-duration: var(--md-sys-motion-spring-default-${kind}-duration);`,
    `  --bb-spring-${kind}-fast: var(--md-sys-motion-spring-fast-${kind}-easing);`,
    `  --bb-spring-${kind}-fast-duration: var(--md-sys-motion-spring-fast-${kind}-duration);`,
  );
}
lines.push(END);

const region = lines.join("\n");
const start = source.indexOf(START);
const next =
  start === -1
    ? source.replace(
        /(  --md-sys-motion-spring-slow-effects-stiffness: [\d.]+;\n)/,
        `$1${region}\n`,
      )
    : source.slice(0, start) +
      region +
      source.slice(source.indexOf(END) + END.length);

await writeFile(PATH, next);
console.log("Spring easings written to src/tokens.css.");
